import csv
import hashlib
import json
import random
import shutil
from pathlib import Path

import yaml
from PIL import Image, UnidentifiedImageError

from visualguard.settings import project_path

NAMES = {0: "person", 1: "head", 2: "helmet", 3: "vest"}


def prepare(manifest: Path, output: Path, seed: int = 42) -> dict:
    """Manifest paths are relative to its directory; split whole scenes, never frames."""
    manifest = project_path(manifest)
    output = project_path(output)
    if output.exists() and any(output.iterdir()):
        raise ValueError("Output directory must be empty; existing splits will not be overwritten")
    with manifest.open(newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise ValueError("Manifest is empty")
    hashes = set()
    validated = []
    for row in rows:
        if any(
            not row.get(key, "").strip() for key in ("image", "label", "scene", "source", "license")
        ):
            raise ValueError("Each manifest row needs image,label,scene,source,license")
        image = project_path(manifest.parent / row["image"])
        label = project_path(manifest.parent / row["label"])
        if image.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
            raise ValueError("Images must be JPEG or PNG")
        try:
            with Image.open(image) as decoded:
                decoded.verify()
        except (OSError, UnidentifiedImageError, Image.DecompressionBombError) as exc:
            raise ValueError(f"Invalid image: {image.name}") from exc
        digest = hashlib.sha256(image.read_bytes()).hexdigest()
        if digest in hashes:
            raise ValueError("Duplicate image content in manifest; deduplicate before splitting")
        hashes.add(digest)
        for line in label.read_text(encoding="utf-8").splitlines():
            parts = line.split()
            if len(parts) != 5:
                raise ValueError(f"Invalid YOLO label in {label.name}")
            class_id, x, y, width, height = map(float, parts)
            if class_id not in NAMES or any(not 0 <= value <= 1 for value in (x, y, width, height)):
                raise ValueError(f"Invalid class or normalized box in {label.name}")
            if (
                width <= 0
                or height <= 0
                or x - width / 2 < -1e-6
                or (x + width / 2 > 1.000001 or y - height / 2 < -1e-6 or y + height / 2 > 1.000001)
            ):
                raise ValueError(f"Box extends outside image in {label.name}")
        validated.append((row, image, label, digest))
    scenes = sorted({row["scene"] for row in rows})
    if len(scenes) < 3:
        raise ValueError("At least three independent scenes are needed for train/val/test")
    random.Random(seed).shuffle(scenes)
    n_test = max(1, round(len(scenes) * 0.15))
    n_val = max(1, round(len(scenes) * 0.15))
    assignment = {
        scene: "test" if index < n_test else "val" if index < n_test + n_val else "train"
        for index, scene in enumerate(scenes)
    }
    output.mkdir(parents=True, exist_ok=True)
    records = []
    for row, image, label, digest in validated:
        split = assignment[row["scene"]]
        image_dir, label_dir = output / "images" / split, output / "labels" / split
        image_dir.mkdir(parents=True, exist_ok=True)
        label_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(image, image_dir / f"{digest}{image.suffix.lower()}")
        shutil.copy2(label, label_dir / f"{digest}.txt")
        records.append({**row, "sha256": digest, "split": split})
    (output / "dataset.yaml").write_text(
        yaml.safe_dump(
            {
                "path": str(output),
                "train": "images/train",
                "val": "images/val",
                "test": "images/test",
                "names": NAMES,
            }
        ),
        encoding="utf-8",
    )
    report = {
        "seed": seed,
        "scenes": assignment,
        "images": records,
        "note": "Manifest provenance is user-supplied, not an independent license verification.",
    }
    (output / "split_manifest.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


def verified_config(path: Path) -> Path:
    path = project_path(path)
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict) or set(config) != {"path", "train", "val", "test", "names"}:
        raise ValueError("Use the dataset.yaml generated by prepare_dataset.py; no download hooks")
    if config["names"] != NAMES:
        raise ValueError("Dataset classes must use the canonical four-label mapping")
    root = project_path(config["path"])
    for split in ("train", "val", "test"):
        target = project_path(root / config[split])
        if not target.is_dir() or not any(target.iterdir()):
            raise ValueError(f"Empty or missing {split} directory")
    return path
